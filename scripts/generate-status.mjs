// Generates src/status.generated.ts from Node's http.STATUS_CODES.
// Run with `npm run generate:status`; the output is committed so builds are reproducible.
import { STATUS_CODES } from 'node:http';
import { writeFileSync } from 'node:fs';

export function toCamelCase(text) {
    const words = text.replace(/'/g, '').split(/[^A-Za-z0-9]+/).filter(Boolean);
    return words
        .map((word, i) => i === 0
            ? word.toLowerCase()
            : word[0].toUpperCase() + word.slice(1).toLowerCase())
        .join('');
}

const entries = Object.entries(STATUS_CODES)
    .map(([code, text]) => ({ code: Number(code), text, name: toCamelCase(text) }));

const names = new Set();
for (const { name, code } of entries) {
    if (names.has(name))
        throw new Error(`Duplicate status name "${name}" (${code})`);
    names.add(name);
}

const body = entries
    .map(({ code, text, name }) => `    { code: ${code}, name: '${name}', text: ${JSON.stringify(text)} },`)
    .join('\n');

writeFileSync(new URL('../src/status.generated.ts', import.meta.url), `// Generated by scripts/generate-status.mjs. Do not edit.

export const STATUSES = [
${body}
] as const;

export type Status = (typeof STATUSES)[number];
export type StatusCode = Status['code'];
export type StatusName = Status['name'];
`);

console.log(`Generated ${entries.length} statuses`);
